#define DOWN 'N'
#define RIGHT 'W'
#define LEFT 'E'
#define UP 'S'

int dirs[4][2] = {
	{1, 0} , {-1, 0},
	{0 ,1}, {0, -1}
};

char temp[5] = "NSWE";

int to_idx(char dir) {
	switch (dir) {
	case 'N': return 0;
	case 'S' : return 1;
	case 'W' : return 2;
	case 'E' : return 3;
	default: return -1;
	}
}

pair<bool, pair<char, int>> yes(vector<string>& maze, char dir, int pos, int cnt) {

	int r = maze.size();
	int c = maze[0].size();

	vector<vector<bool>> vis(r, vector<bool>(c, false));

	int i, j;
	switch (dir) {
		case DOWN: 
			i = 0;
			j = pos;
			break;
		case RIGHT: 
			j = 0;
			i = pos;
			break;
		case UP: 
			i = r - 1;
			j = pos;
			break;
		default : 
			j = c - 1;
			i = pos;
			break;
	}

	while (true) {
		int dx, dy;
		switch (dir) {
			case DOWN: 
				dy = dirs[0][0];
				dx = dirs[0][1];
				break;
			case RIGHT: 
				dy = dirs[2][0];
				dx = dirs[2][1];
				break;
			case UP: 
				dy = dirs[1][0];
				dx = dirs[1][1];
				break;
			default : 
				dy = dirs[3][0];
				dx = dirs[3][1];
				break;
		}

		while (i >= 0 && i < r && j >= 0 && j < c && maze[i][j] == '.') {
			j += dx;
			i += dy;
		}

		if (!(i >= 0 && i < r && j >= 0 && j < c)) break;

		if (!vis[i][j]) {
			vis[i][j] = true;
			--cnt;
		}

		if (maze[i][j] == '/') {
			switch (dir) {
				case DOWN: 
					dir = LEFT;
					--j;
					break;
				case RIGHT: 
					dir = UP;
					--i;
					break;
				case UP: 
					dir = RIGHT;
					++j;
					break;
				default : 
					dir = DOWN;
					++i;
					break;
			}
		} else if (maze[i][j] == '\\') {
			switch (dir) {
				case DOWN: 
					dir = RIGHT;
					++j;
					break;
				case RIGHT: 
					dir = DOWN;
					++i;
					break;
				case UP: 
					dir = LEFT;
					--j;
					break;
				default : 
					dir = UP;
					--i;
					break;
			}
		}
	}

	pair<char, int> res;
	char hmm; int hmm_pos;
	if (i < 0) {
		hmm = DOWN;
		hmm_pos = j;
	} else if (i >= r) {
		hmm = UP;
		hmm_pos = j;
	} else if (j < 0) {
		hmm = RIGHT;
		hmm_pos = i;
	} else if (j >= c) {
		hmm = LEFT;
		hmm_pos = i;
	}

	res = {hmm, hmm_pos};

	
	return {cnt <= 0, res};
}

void solve() {
	int r, c;
	cin >> r >> c;
	vector<string> s(r);

	int cnt = 0;
	int i = 0, j = 0;
	int pos_i, pos_j;

	for (auto & e : s) {
		cin >> e;
		for (auto d : e) {
			if (d == '\\' || d == '/') {
				++cnt;
				pos_i = i;
				pos_j = j;
			}
			++j;
		}
		++i;
		j = 0;
	}

	if (cnt == 1) {
		++pos_j, ++pos_i;
		printf("4\n"
			"N%d S%d W%d E%d",
			pos_j, pos_j, pos_i, pos_i
			);
		return;
	}
	vector<vector<bool>> ye(4, vector<bool>(max(r,c), false));
	vector<pair<char, int>> ans;

	bool found = false;
	
	for (i = 0; i < c; ++i) {
		for (j = 0; j < 2; ++j) {
			if (ye[j][i]) continue;

			auto[a, b] = yes(s, temp[j], i, cnt);
			if (a) {
				ans.push_back({temp[j], i});
				ans.push_back(b);
				found = true;
			}

			ye[to_idx(b.first)][b.second] = true;
			if (found) break;
		}
		if (found) break;
	}

	if (!found)
	for (i = 0; i < r; ++i) {
		for (j = 2; j < 4; ++j) {
			if (ye[j][i]) continue;

			auto[a, b] = yes(s, temp[j], i, cnt);
			if (a) {
				ans.push_back({temp[j], i});
				ans.push_back(b);
				found = true;
			}
			
			ye[to_idx(b.first)][b.second] = true;
			if (found) break;
		}
		if (found) break;
	}

	cout << ans.size() << '\n';
	for (auto e : ans) 
		cout << e.first << e.second + 1 << ' ';
}

int main() {
    fast_io;
    int t = 1;
    // cin >> t;
    while (t--) {
        solve();

        // if (solve()) cout << "Yes\n";
        // else cout << "No\n";
    }
    return 0;
}
    
